# Сколько осталось до старта следующего раунда PancakeSwap Prediction (BNB/USD).
# Только stdlib. Время — с сайта Binance (пара листится там), границы раунда —
# из контракта: «300 секунд mod» врёт, реальный шаг раундов 304-306 с и уплывает.
# Селекторы функций контракта предвычислены через ethers.Interface.
import json
import os
import sys
import re
import urllib.request


# --- Не создавать папки __pycache__ (bytecode-кэш) ---
sys.dont_write_bytecode = True
os.environ["PYTHONDONTWRITEBYTECODE"] = "1"

PREDICTION = '0x18B2A687610328590Bc8F2e5fEdDe3b582A49cdA'
SEL_CURRENT_EPOCH = '0x76671808'  # currentEpoch()
SEL_ROUNDS = '0x8c65c81f'  # rounds(uint256)
RPCS = ['https://bsc-dataseed.binance.org/', 'https://bsc-dataseed1.defibit.io/', 'https://rpc.ankr.com/bsc']
TIME_HOSTS = ['https://data-api.binance.vision', 'https://api.binance.com']

# Файл-константа — от корня проекта, с прямыми слешами (как во всём проекте)
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))  # корень проекта
OUT = 'DASHBOARD.py'
OUT = os.path.join(PROJECT_ROOT, OUT.replace('/', os.sep))
HEADER = '#generated by get_time_from_website.py: TIME_LEFT = M.SS, 2.21 = 2 min 21 sec'
TIME_LEFT_RE = re.compile(r'\s*TIME_LEFT\s*=')


def http_json(url, timeout=15):
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return json.load(r)


def binance_now_ms():
    last = None
    for host in TIME_HOSTS:
        try:
            return int(http_json(host + '/api/v3/time')['serverTime'])
        except Exception as e:  # узел может не ответить — пробуем следующий
            last = e
    raise RuntimeError('bin time failed: %r' % last)


def rpc(url, data_hex):
    body = json.dumps({'jsonrpc': '2.0', 'id': 1, 'method': 'eth_call',
                       'params': [{'to': PREDICTION, 'data': data_hex}, 'latest']}).encode()
    req = urllib.request.Request(url, data=body, headers={'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.load(r)['result']


def chain_call(data_hex):
    last = None
    for url in RPCS:
        try:
            res = rpc(url, data_hex)
            if res and res != '0x':
                return bytes.fromhex(res[2:])
            last = 'empty result'
        except Exception as e:
            last = e
    raise RuntimeError('rpc failed: %r' % last)


def word(raw, i):
    return int.from_bytes(raw[i * 32:(i + 1) * 32], 'big')


def write_const(path, time_left):
    # Меняем только строку TIME_LEFT; остальное содержимое файла не трогаем,
    # а если файла нет — создаём с шапкой-комментарием.
    line = 'TIME_LEFT = %s' % time_left
    try:
        with open(path, encoding='utf-8') as f:
            lines = f.read().splitlines()
    except FileNotFoundError:
        lines = [HEADER]

    out, replaced = [], False
    for old in lines:
        if TIME_LEFT_RE.match(old):
            if replaced:  # повторные TIME_LEFT-строки — мусор от прошлых версий
                continue
            replaced, old = True, line
        out.append(old)
    if not replaced:
        out.append(line)
    if out == lines:  # значение не поменялось — файл не переписываем
        return

    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')


def main():
    now_s = binance_now_ms() / 1000
    epoch = word(chain_call(SEL_CURRENT_EPOCH), 0)
    raw = chain_call(SEL_ROUNDS + format(epoch, '064x'))
    lock_ts, close_ts = word(raw, 2), word(raw, 3)

    # Следующий раунд открывается для ставок, когда у текущего закрываются ставки.
    # Если активный уже локнут ("Live") — следующий откроется в его closeTimestamp.
    next_open_ts = lock_ts if now_s < lock_ts else close_ts
    remain = max(0, round(next_open_ts - now_s)) if now_s < close_ts else 0
    # TIME_LEFT = минуты.секунды двумя цифрами: 2.21 = 2 мин 21 с. Пишем строкой,
    # иначе литерал 2.50 питон при импорте съест как 2.5 = «2:05».
    time_left = '%d.%02d' % divmod(remain, 60)

    write_const(OUT, time_left)


if __name__ == '__main__':
    main()
